/** A collapsible "how to read" box at the top of a tab or page; the state is remembered for all of them. */
export function Guide({ id }: { id: keyof typeof GUIDES }) {
  const g = GUIDES[id];
  const [open, setOpen] = useState(() => {
    try { return localStorage.getItem("ram.guides") === "open"; } catch { return false; }
  });
  if (!g) return null;
  return (
    <details className="guide" open={open} onToggle={(e) => {
      const v = (e.target as HTMLDetailsElement).open;
      setOpen(v);
      try { localStorage.setItem("ram.guides", v ? "open" : "closed"); } catch { /* storage blocked */ }
    }}>
      <summary><span className="guide-q">Как читать</span> {g.question}</summary>
      <ul>{g.points.map((p, i) => <li key={i}>{p}</li>)}</ul>
      {g.traps && <p className="guide-trap"><b>Осторожно:</b> {g.traps.map((t, i) => <span key={i}>{t} </span>)}</p>}
      <p className="guide-more">Термины с пунктирным подчёркиванием объясняются при наведении. Все определения — на странице <a href="#/help">«Справка»</a>, формулы — в <a href="#/theory">«Теории»</a>.</p>
    </details>
  );
}

