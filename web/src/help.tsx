/** A term with its definition on hover, focus or tap; Enter opens the help page at it. */
export function Term({ k, children }: { k: string; children?: ReactNode }) {
  const g = GLOSSARY[k];
  const ref = useRef<HTMLSpanElement>(null);
  const timer = useRef<number | undefined>(undefined);
  const [pos, setPos] = useState<{ x: number; y: number; up: boolean } | null>(null);
  const id = useId();
  useEffect(() => {
    if (!pos) return;
    const off = () => setPos(null);
    window.addEventListener("scroll", off, true);
    window.addEventListener("resize", off);
    return () => { window.removeEventListener("scroll", off, true); window.removeEventListener("resize", off); };
  }, [pos]);
  if (!g) return <>{children}</>;
  const open = () => {
    window.clearTimeout(timer.current);
    const r = ref.current?.getBoundingClientRect();
    if (!r) return;
    const width = Math.min(340, window.innerWidth - 16);
    const up = r.bottom + 220 > window.innerHeight && r.top > 240;
    setPos({ x: Math.max(8, Math.min(r.left, window.innerWidth - width - 8)), y: up ? r.top - 6 : r.bottom + 6, up });
  };
  const close = () => { timer.current = window.setTimeout(() => setPos(null), 150); };
  return (
    <>
      <span ref={ref} className="term" tabIndex={0} aria-describedby={pos ? id : undefined}
        onMouseEnter={open} onMouseLeave={close} onFocus={open} onBlur={close}
        onClick={(e) => { e.stopPropagation(); if (pos) setPos(null); else open(); }}
        onKeyDown={(e) => {
          if (e.key === "Escape") setPos(null);
          if (e.key === "Enter") { e.preventDefault(); window.location.hash = `#/help/${k}`; }
        }}>{children ?? g.title}</span>
      {pos && createPortal(
        <div id={id} role="tooltip" className={"term-tip" + (pos.up ? " up" : "")} style={{ left: pos.x, top: pos.y }}
          onMouseEnter={() => window.clearTimeout(timer.current)} onMouseLeave={close}>
          <b>{g.title}</b>
          <p>{g.short}</p>
          <a href={`#/help/${k}`} onClick={() => setPos(null)}>Подробнее в справке →</a>
        </div>, document.body)}
    </>
  );
}

